function variant(
  productId: string,
  label: string,
  price: number,
  stockQty: number,
  compareAtPrice: number | null = null
) {
  return {
    id: `${productId}_${label.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
    productId,
    label,
    price,
    compareAtPrice,
    stockQty,
    sku: `SKU-${productId.toUpperCase()}-${label.toUpperCase().replace(/[^A-Z0-9]+/g, "")}`,
  };
}

